const paramTema = new URLSearchParams(location.search).get('tema');
let actual = TEMAS[paramTema] ?? TEMAS[localStorage.getItem(CLAVE_STORAGE)] ?? TEMAS.dracula;

export const temaActual = () => actual;

export function aplicarTema(id) {
  const t = TEMAS[id] ?? TEMAS.dracula;
  actual = t;
  try {
    localStorage.setItem(CLAVE_STORAGE, t.id);
  } catch {}
  const root = document.documentElement;
  root.style.colorScheme = t.esClaro ? 'light' : 'dark';
  root.dataset.tema = t.id;
  for (const [k, v] of Object.entries(t.css)) root.style.setProperty(k, v);
  if (t.materias) {
    for (const [matId, col] of Object.entries(t.materias)) {
      if (MATERIAS[matId]) MATERIAS[matId].color = col;
      root.style.setProperty(`--mat-${matId}`, col);
    }
  }
  window.dispatchEvent(new CustomEvent('cambio-tema', { detail: t }));
  return t;
}
